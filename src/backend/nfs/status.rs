pub(super) fn errno(error: i32) -> Status {
    match error {
        libc::EPERM => PERM,
        libc::ENOENT => NOENT,
        libc::EIO => IO,
        libc::ENXIO => 6,
        libc::EACCES => ACCESS,
        libc::EEXIST => EXIST,
        libc::EXDEV => 18,
        libc::ENOTDIR => NOTDIR,
        libc::EISDIR => ISDIR,
        libc::EINVAL => INVAL,
        libc::EFBIG | libc::EOVERFLOW => FBIG,
        libc::ENOSPC => 28,
        libc::EROFS => ROFS,
        libc::EMLINK => 31,
        libc::ENAMETOOLONG => NAMETOOLONG,
        libc::ENOTEMPTY => 66,
        libc::EDQUOT => 69,
        libc::ESTALE => STALE,
        libc::EOPNOTSUPP | libc::ENOTSUP | libc::ENOSYS => NOTSUPP,
        libc::EINTR | libc::EAGAIN | libc::EBUSY => DELAY,
        libc::EBADF => OPENMODE,
        libc::ELOOP => SYMLINK,
        _ => IO,
    }
}
